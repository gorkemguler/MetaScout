"""PDF report, built from a run's report.json payload.

Reading report.json (rather than a live ScanFindings) is deliberate: it's the
one artifact every past run already has on disk, so the same code produces a
PDF for a scan that finished months ago and for one that just ended.

Optional: needs the [pdf] extra (reportlab). reportlab ships its own
Bitstream Vera TTF, which covers Turkish/Latin-Extended glyphs, so the PDF
looks the same on macOS, Linux and Windows with no system font hunting.
"""
